typedef signed char SOCKET;

/* tcp.h (WIZNET) return: <= 32767 -> socket/count, else 0x8000|errno */
#define NET_OK(t) ((t) <= 32767)
#define NET_ERR(t) ((unsigned char)((t) & 255))
#define NET_SOCK(t) ((signed char)(((t) >> 8) & 255))

