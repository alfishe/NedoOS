static void set_addr(struct sockaddr_in *ia, unsigned int port)
{
	ia->family = AF_INET;
	ia->porth = (unsigned char)(port >> 8);
	ia->portl = (unsigned char)port;
}

static SOCKET open_sock(unsigned char family, unsigned char proto)
{
	unsigned int todo = OS_NETSOCKET(((unsigned int)family << 8) | proto);
	if (NET_OK(todo))
		return NET_SOCK(todo);
	return (SOCKET)(0 - NET_ERR(todo));
}

static void close_sock(SOCKET *s)
{
	if (*s)
	{
		OS_NETSHUTDOWN((unsigned char)*s, 0);
		*s = 0;
	}
}

static int tcp_send(SOCKET s, const void *buf, unsigned int size)
{
	unsigned int todo;
	readStruct.socket = (unsigned char)s;
	readStruct.BufAdr = (unsigned int)buf;
	readStruct.bufsize = size;
	readStruct.protocol = SOCK_STREAM;
	todo = OS_WIZNETWRITE(&readStruct);
	if (NET_OK(todo))
		return (int)todo;
	return 0 - (int)NET_ERR(todo);
}

static int tcp_recv(SOCKET s, void *buf, unsigned int size)
{
	unsigned int todo;
	readStruct.socket = (unsigned char)s;
	readStruct.BufAdr = (unsigned int)buf;
	readStruct.bufsize = size;
	readStruct.protocol = SOCK_STREAM;
	todo = OS_WIZNETREAD(&readStruct);
	if (NET_OK(todo))
		return (int)todo;
	return 0 - (int)NET_ERR(todo);
}

static int udp_recvfrom(SOCKET s, void *buf, unsigned int size, struct sockaddr_in *from)
{
	unsigned int todo;
	readStruct.socket = (unsigned char)s;
	readStruct.BufAdr = (unsigned int)buf;
	readStruct.bufsize = size;
	readStruct.protocol = SOCK_DGRAM;
	todo = OS_WIZNETREAD_UDP(&readStruct, from);
	if (NET_OK(todo))
		return (int)todo;
	return 0 - (int)NET_ERR(todo);
}

static int udp_sendto(SOCKET s, const void *buf, unsigned int size, struct sockaddr_in *to)
{
	unsigned int todo;
	readStruct.socket = (unsigned char)s;
	readStruct.BufAdr = (unsigned int)buf;
	readStruct.bufsize = size;
	readStruct.protocol = SOCK_DGRAM;
	todo = OS_WIZNETWRITE_UDP(&readStruct, to);
	if (NET_OK(todo))
		return (int)todo;
	return 0 - (int)NET_ERR(todo);
}

#define VIZ_H 12
#define VIZ_Y0 6
#define VIZ_X0 35
#define VIZ_DX 4

static unsigned char viz_level[3];	/* displayed height 0..VIZ_H */
static unsigned char viz_drawn[3];	/* last drawn height */
static long viz_tick;			/* last time() processed */

/* AY volume reg 8/9/10: bit 4 = envelope mode (low nibble is ignored);
   the real envelope level is generated by the AY and cannot be read back,
   so an enveloped channel is shown as loud. */
static unsigned char viz_target(unsigned char vol)
{
	unsigned char v;
	if (vol & 0x10u)
		v = 15u;
	else
		v = (unsigned char)(vol & 15u);
	return (unsigned char)(((unsigned int)v * VIZ_H) / 15u);
}

static void viz_col(unsigned char x, unsigned char level, unsigned char idx)
{
	unsigned char i, color, filled, was;
	if (level == viz_drawn[idx])
		return;
	for (i = 0; i < VIZ_H; i++)
	{
		filled = (unsigned char)(i >= (VIZ_H - level));
		was = (unsigned char)(i >= (VIZ_H - viz_drawn[idx]));
		if (filled == was)
			continue;
		OS_SETXY(x, VIZ_Y0 + i);
		if (filled)
		{
			if (i >= 6)
				color = 0x04;	/* green  */
			else if (i >= 2)
				color = 0x06;	/* yellow */
			else
				color = 0x02;	/* red    */
			OS_SETCOLOR(color);
			putchar(219);
			putchar(219);
		}
		else
		{
			OS_SETCOLOR(0x07);
			putchar(32);
			putchar(32);
		}
	}
	viz_drawn[idx] = level;
}

static void viz_update(void)
{
	unsigned char a, b, c;
	long now;
	a = datasoc ? viz_target(ay_vol_a) : 0;
	b = datasoc ? viz_target(ay_vol_b) : 0;
	c = datasoc ? viz_target(ay_vol_c) : 0;
	now = time();
	if (now != viz_tick)
	{
		viz_tick = now;
		/* fall one row per 1/50 s tick */
		if (viz_level[0] > a)
			viz_level[0]--;
		if (viz_level[1] > b)
			viz_level[1]--;
		if (viz_level[2] > c)
			viz_level[2]--;
	}
	/* attack is instant */
	if (a > viz_level[0])
		viz_level[0] = a;
	if (b > viz_level[1])
		viz_level[1] = b;
	if (c > viz_level[2])
		viz_level[2] = c;
	viz_col(VIZ_X0, viz_level[0], 0);
	viz_col(VIZ_X0 + VIZ_DX, viz_level[1], 1);
	viz_col(VIZ_X0 + 2 * VIZ_DX, viz_level[2], 2);
}

static void show_banner(void)
{
	unsigned char len, x;
	len = (unsigned char)sprintf(banner_buf, "AYNET server: waiting music stream on port: %u ", serve_port);
	x = (len < 80u) ? (unsigned char)((80u - len) / 2u) : 0u;
	OS_CLS(0);
	OS_SETXY(x, 0);
	puts(banner_buf);
}

unsigned char scrredraw(void)
{
	show_banner();
	return 0;
}

/* e==0: clean quit (Esc in bdosgetkey passes 0);
   e!=0: error message string from our own exit("...") calls. */
void exit(int e)
{
	OS_SETMUSIC(int_null, app_pages.pgs.window_1);
	shutup();
	close_sock(&cmds);
	close_sock(&datasoc);
	close_sock(&udps);
	if (e != 0)
	{
		OS_SETGFX(6);
		puts((char *)e);
		puts("Press any key");
		getchar();
	}
	((void (*)(int))0x0000)(0);
}

void initMCU(void)
{
	YIELD();
	app_pages.l = OS_GETMAINPAGES();
	// OS_SETMUSIC(int_play, app_pages.pgs.window_1);
	OS_SETGFX(6);
	OS_CLS(0);
}

void putserr(const char *s1, const char *s2)
{
	if (grmod == 0)
	{
		OS_SETGFX(6);
		grmod = 1;
	}
	printf("Error: %s %s!", s1, s2);
}

C_task main(int argc, char *argv[])
{
	int l = 1;
	unsigned int todo;
	initMCU();
	ptr_out_rx = buf_rx;
	ptr_in_rx = buf_rx + sizeof(buf_rx);
	set_addr(&web_ia, 16729); //'AY' chars
	set_addr(&udpr_ia, 16729);
	while (l != argc)
	{
		char *p = argv[l];
		if (p[0] != '-')
			exit((int)"Wrong parameter");
		switch (p[1] & 0xdf)
		{
		case 'P':
			serve_port = (unsigned int)strtoul(p + 2, &ptr, 10);
			set_addr(&web_ia, serve_port);
			break;
		default:
			exit((int)"Wrong parameter");
		}
		l++;
	}
	show_banner();
	cmds = open_sock(AF_INET, SOCK_STREAM);

	OS_BIND((unsigned char)cmds, &web_ia);
	OS_LISTEN((unsigned char)cmds);
	while (1)
	{
		viz_update();
		if (datasoc == 0)
		{
			if (udps == 0)
			{
				udps = open_sock(AF_INET, SOCK_DGRAM);
				OS_BIND((unsigned char)udps, &udpr_ia);
			}
			l = udp_recvfrom(udps, udp_buf, sizeof(udp_buf), &udps_ia);
			if (l > 0)
			{
				udp_buf[l] = 0x00;
				puts(udp_buf);
				udp_sendto(udps, msg_hello + 2, 8, &udps_ia);
			}
			if (cmds == 0)
			{
				cmds = open_sock(AF_INET, SOCK_STREAM);
				OS_BIND((unsigned char)cmds, &web_ia);
				OS_LISTEN((unsigned char)cmds);
			}
			todo = OS_ACCEPT((unsigned char)cmds);
			if (NET_OK(todo))
			{
				datasoc = NET_SOCK(todo);
			}
			else
			{
				datasoc = (SOCKET)(0 - NET_ERR(todo));
			}
			if (datasoc < 0)
			{
				datasoc = 0;
				OS_SETMUSIC(int_null, app_pages.pgs.window_1);
				if (NET_ERR(todo) != ERR_EAGAIN)
				{
					close_sock(&cmds);
				}
				else
				{
					_low_level_get();
				}
				continue;
			}
			else
			{ // to do else
				close_sock(&cmds);
				close_sock(&udps);
				tcp_send(datasoc, msg_hello, 9);
				ptr_in_rx = buf_rx;
				ptr_out_rx = NULL;
				last_rx_tick = time();
				OS_SETMUSIC(int_play, app_pages.pgs.window_1);
			}
		}
		if (datasoc != 0 && (time() - last_rx_tick) >= 50L)
		{
			OS_SETMUSIC(int_null, app_pages.pgs.window_1);
			shutup();
			close_sock(&datasoc);
			continue;
		}
		if (flag_int_change)
		{
			flag_int_change = 0;
			if (flag_syncrply == 2)
			{
				tcp_send(datasoc, msg_framesync, 10);
			}
			else
			{
				tcp_send(datasoc, msg_framesync, 5);
			}
			flag_syncrply = 0;
		}
		if (ptr_out_rx < ptr_in_rx)
		{
			l = tcp_recv(datasoc, ptr_in_rx, buf_rx + sizeof(buf_rx) - ptr_in_rx);
		}
		else if (ptr_out_rx > ptr_in_rx)
		{
			l = tcp_recv(datasoc, ptr_in_rx, ptr_out_rx - ptr_in_rx);
		}
		else
		{
			continue;
		}
		if (l < 0)
		{
			if (-l == ERR_EAGAIN)
			{
				_low_level_get();
				continue;
			}
			OS_SETMUSIC(int_null, app_pages.pgs.window_1);
			shutup();
			close_sock(&datasoc);
			continue;
		}
		// тут складываем пакет в буфер
		last_rx_tick = time();
		ptr_increment(l);
	}
}
