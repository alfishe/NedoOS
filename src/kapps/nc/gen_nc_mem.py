#!/usr/bin/env python3
"""Parse IAR xlink cout.html and emit nc_mem.h with used/free sizes."""

import re
import sys


def dec_html_num(s):
    s = s.replace("\xa0", " ")
    s = re.sub(r"&nbsp;", " ", s)
    s = s.replace(" ", "")
    return int(s)


def parse_hex(s):
    return int(s.strip(), 16)


def find_segment_hi(html, name):
    pat = (
        rf"<td rowspan=1 ><font size=2>{name}</font>\s*"
        rf"<td rowspan=1 ><font size=2></font>\s*"
        rf"<td align=center colspan=2><font size=2>([0-9A-Fa-f]+) - ([0-9A-Fa-f]+)</font>"
    )
    m = re.search(pat, html, re.S | re.I)
    if not m:
        raise SystemExit(f"segment {name!r} not found in map")
    return parse_hex(m.group(2))


def find_mem_summary(html, kind):
    pat = (
        rf"<td align=right valign=top>([0-9&nbsp;]+)</td>\s*"
        rf"<td valign=top>bytes</td>\s*"
        rf"<td valign=top>of</td>\s*"
        rf"<td valign=top>{kind}</td>"
    )
    m = re.search(pat, html, re.S | re.I)
    if not m:
        raise SystemExit(f"{kind} memory summary not found")
    return dec_html_num(m.group(1))


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_nc_mem.py obj/cout.html nc_mem.h")

    html = open(sys.argv[1], "r", encoding="latin-1", errors="replace").read()

    main_used_end = find_segment_hi(html, "CSTACK")
    res_code_end = find_segment_hi(html, "CODE_RESIDENT")
    main_code_bytes = find_mem_summary(html, "CODE")
    main_data_bytes = find_mem_summary(html, "DATA")

    main_base = 0x0100
    main_limit = 0xBFFF
    res_base = 0xC000
    res_limit = 0xFFFF

    main_free = main_limit - main_used_end
    res_code_used = res_code_end - res_base + 1
    res_code_free = res_limit - res_code_end

    out = f"""/* Auto-generated by gen_nc_mem.py from IAR link map. Do not edit. */
#ifndef NC_MEM_H
#define NC_MEM_H

#define NC_MAIN_BASE           0x{main_base:04X}u
#define NC_MAIN_LIMIT          0x{main_limit:04X}u
#define NC_MAIN_SIZE           0x{main_limit - main_base + 1:04X}u
#define NC_MAIN_USED_END       0x{main_used_end:04X}u /* CSTACK top */
#define NC_MAIN_FREE           0x{main_free:04X}u
#define NC_MAIN_CODE_BYTES     {main_code_bytes}u
#define NC_MAIN_DATA_BYTES     {main_data_bytes}u

#define NC_RES_BASE            0x{res_base:04X}u
#define NC_RES_LIMIT           0x{res_limit:04X}u
#define NC_RES_SIZE            0x{res_limit - res_base + 1:04X}u
#define NC_RES_CODE_END        0x{res_code_end:04X}u
#define NC_RES_CODE_USED       0x{res_code_used:04X}u
#define NC_RES_CODE_FREE       0x{res_code_free:04X}u

#endif
"""
    open(sys.argv[2], "w", encoding="ascii", newline="\n").write(out)
    print(
        f"nc_mem: main code {main_code_bytes} data {main_data_bytes} "
        f"free 0x{main_free:X}; resident code used 0x{res_code_used:X} free 0x{res_code_free:X}"
    )


if __name__ == "__main__":
    main()
